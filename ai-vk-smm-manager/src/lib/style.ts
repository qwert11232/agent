/** Удаляет всё, что VK покажет как «звёздочки» и хештеги, какими бы ни были ответы ИИ. */
export function sanitizePostText(text: string): string {
  let t = text;
  // markdown-полужирный и курсив
  t = t.replace(/\*\*([\s\S]+?)\*\*/g, "$1").replace(/\*([^*\n]+?)\*/g, "$1").replace(/__([\s\S]+?)__/g, "$1");
  // заголовки-решётки и markdown-кавычки кода
  t = t.replace(/^[#]{1,6}\s+/gm, "").replace(/```[\s\S]*?```/g, "").replace(/`([^`\n]+)`/g, "$1");
  // эмодзи-маркеры списков в начале строк
  t = t.replace(/^\s*[🔹🔸▶️👉➡✔️✅⚡️•◾◽]\s+/gm, "- ");
  // хештеги: удаляем все токены «#слово», пустые строки подчистить
  t = t.replace(/#[\p{L}\p{N}_]+/gu, "");
  // Плейсхолдеры числовых утверждений «на N%» — заменяем на обобщённые, под запретом стиля.
  t = t
    .replace(/на\s+\d+[\d.,]*\s*%/gi, "заметно")
    .replace(/на\s+\d+\s+процент[а-яу]*/gi, "заметно")
    .replace(/\d+[\d.,]*\s*%/g, "например, в наших проектах есть сдвиг")
    .replace(/\b(CTR|конверси[яею] выросл[ао]|открываемость (выросла|упала)|продажи (выросли|упали))\s+на\s+[а-я]+\s+процент[а-я]*/gi, "заметно улучшились динамики");
  // Любые фейковые проценты в первом предложении поста — удаляем предложение.
  const firstLine = t.split("\n", 1)[0];
  if (/\d+\s*%/.test(firstLine)) {
    t = t.split("\n").slice(1).join("\n");
  }
  // подчистить пустые тире-строки и повторные пустые строки
  t = t.replace(/^\s*[-–—]\s*$/gm, "").replace(/\n{3,}/g, "\n\n");
  return t.trim();
}
