/** Слова, которые делают расчёт «условным»: числа рядом с ними не считаются выдуманными. */
const HYPOTHETICAL_RE = /(допустим|предположим|скажем|условн|если(?![а-яё])|например|прикиньте|посчитаем|представим)/i;

const MONTHS_RE = /^\s*(январ|феврал|март|апрел|ма[яй]|июн|июл|август|сентябр|октябр|ноябр|декабр)/i;
/** Длительности («за 10 минут», «2 недели») - это усилие в инструкции, а не заявленный результат. */
const DURATION_RE = /^\s*(сек|мин|час|дн|день|недел|мес)/i;
const UNIT_RE = /^\s*(%|процент|₽|руб|тыс|млн|млрд|раза?(?![а-яё])|заяв|клиент|посетител|переход|лид|продаж|заказ|\$|usd|eur)/i;

function digitsKey(tok: string) {
  return tok.replace(/[\s\u00a0]/g, "").replace(",", ".");
}

/** Все числа из текста-источника (банк фактов, свежие данные) в нормализованном виде. */
export function numberSet(source: string): Set<string> {
  const set = new Set<string>();
  for (const m of source.matchAll(/\d+(?:[ \u00a0]\d{3})*(?:[.,]\d+)?/g)) set.add(digitsKey(m[0]));
  return set;
}

/**
 * Числа в тексте, которых нет ни в источнике фактов, ни в «условном» абзаце.
 * Пост с такими числами нельзя отправлять в автоочередь: нужна ручная проверка.
 * Не считаются: нумерация списков, время 12:30, годы, даты («5 октября»), одиночные цифры без единицы.
 */
export function findUnsupportedNumbers(text: string, allowedSource = ""): string[] {
  const allowed = numberSet(allowedSource);
  const bad: string[] = [];
  const paragraphs = text.split(/\n{2,}/);
  for (const para of paragraphs) {
    if (HYPOTHETICAL_RE.test(para)) continue;
    const re = /\d+(?:[ \u00a0]\d{3})*(?:[.,]\d+)?/g;
    let m: RegExpExecArray | null;
    while ((m = re.exec(para))) {
      const tok = m[0];
      const start = m.index;
      const end = start + tok.length;
      const before = para.slice(Math.max(0, start - 1), start);
      const after = para.slice(end);
      // время, десятичные хвосты внутри другого числа
      if (/^:\d/.test(after) || /\d[:.,]$/.test(para.slice(Math.max(0, start - 2), start))) continue;
      if (before === ":" ) continue;
      // нумерация списка в начале строки: «1.», «2)»
      const lineStart = para.lastIndexOf("\n", start) + 1;
      if (para.slice(lineStart, start).trim() === "" && /^[.)]/.test(after)) continue;
      // годы и даты
      const n = Number(digitsKey(tok));
      if (n >= 1900 && n <= 2100 && !UNIT_RE.test(after)) continue;
      if (MONTHS_RE.test(after) || DURATION_RE.test(after)) continue;
      const hasUnit = UNIT_RE.test(after);
      const multi = digitsKey(tok).replace(".", "").length >= 2;
      if (!hasUnit && !multi) continue;
      if (allowed.has(digitsKey(tok))) continue;
      bad.push(`${tok}${hasUnit ? after.match(UNIT_RE)?.[0].trim() ?? "" : ""}`);
    }
  }
  return [...new Set(bad)];
}

/** Удаляет всё, что VK покажет как «звёздочки» и хештеги, какими бы ни были ответы ИИ. */
export function sanitizePostText(text: string): string {
  let t = text.replace(/[\u2010\u2011]/g, "-");
  // markdown-полужирный и курсив
  t = t.replace(/\*\*([\s\S]+?)\*\*/g, "$1").replace(/\*([^*\n]+?)\*/g, "$1").replace(/__([\s\S]+?)__/g, "$1");
  // заголовки-решётки и markdown-кавычки кода
  t = t.replace(/(^|\s)#{2,}(?=\s)/g, "$1");
  t = t.replace(/^[#]{1,6}\s+/gm, "").replace(/```[\s\S]*?```/g, "").replace(/`([^`\n]+)`/g, "$1");
  // эмодзи-маркеры списков в начале строк
  t = t.replace(/^\s*[🔹🔸▶️👉➡✔️✅⚡️•◾◽]\s+/gm, "- ");
  // хештеги: удаляем все токены «#слово»
  t = t.replace(/(^|[\s(])#[\p{L}\p{N}_]+/gu, "$1");
  // Числа НЕ переписываем: подмена «30%» мусорной фразой ломала предложения.
  // Недостоверные числа ловит findUnsupportedNumbers() → пост уходит на ручную проверку.
  t = t.replace(/[ \t]+$/gm, "").replace(/^\s*[-–—]\s*$/gm, "").replace(/\n{3,}/g, "\n\n");
  return t.trim();
}

/** Служебные формулировки, которые не должны попадать в публикацию. */
const LEAK_RE = /(придумай|правдоподобн[а-яёa-z]+ (экспертн|истори)|БАНК ФАКТОВ|ступень призыва|ЛЕСТНИЦА|<<|>>|\{[a-zA-Z_]+\})/i;
export function hasPromptLeak(text: string): boolean {
  return LEAK_RE.test(text);
}

const BANNED_OPENERS_RE =
  /^(друзья|признаюсь честно|сегодня поговорим|сегодня разберём|хочу рассказать|многие думают|дайджест|привет|добрый день|коллеги|а вы знали|представьте|неожиданный факт)/i;

/** Проверка первой строки по тестам хука: длина и запрещённые оболочки. Пусто = всё в порядке. */
export function firstLineProblem(text: string): string {
  const first = text.split("\n").find((l) => l.trim())?.trim() ?? "";
  if (!first) return "пустая первая строка";
  if (BANNED_OPENERS_RE.test(first)) return "первая строка начинается с запрещённой оболочки";
  if (first.length > 110) return "первая строка длиннее 90 знаков";
  return "";
}

/** Первые строки недавних постов (для блока антиповтора). */
export function firstLines(texts: string[], max = 10): string[] {
  return texts
    .map((t) => t.split("\n").find((l) => l.trim())?.trim().replace(/\s+/g, " ").slice(0, 110) ?? "")
    .filter(Boolean)
    .slice(0, max);
}
